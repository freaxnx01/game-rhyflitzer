"""#682: line 133 against the real extract, and the committed timetable against the committed world.

Both halves skip without their input: the regional extract is not in the repo, and the timetable is
generated by hand once per timetable year (see docs/11-pipeline-osm.md)."""
import json
import math
from collections import Counter
from pathlib import Path

import pytest
import shapely

import geo
import osm

PBF = Path(__file__).parents[1] / "cache" / "osm" / "hochrhein.osm.pbf"
DATA = Path(__file__).parents[2] / "data"


@pytest.fixture(scope="module")
def routes():
    if not PBF.exists():
        pytest.skip("regional extract not present")
    w = osm.build_world(PBF, None, geo.DEFAULT_BBOX, geo.DEFAULT_ORIGIN, 30.0, 1000.0,
                        Path(__file__).parents[1] / "anchors.json")
    return {r["id"]: r for r in w["busRoutes"]}


def test_line_133_routes(routes):
    r133 = {i: r for i, r in routes.items() if r["line"] == "133"}
    assert sorted(r133) == [11533940, 11533941]
    for r in r133.values():
        assert r["cut"] == [False, False] and 7000 < r["len"] < 14000
        assert len(r["stops"]) == 11
    assert routes[11533940]["stops"][0]["uic"] == "8500583" and routes[11533940]["stops"][-1]["uic"] == "8572748"
    assert routes[11533941]["stops"][0]["uic"] == "8572748" and routes[11533941]["stops"][-1]["uic"] == "8500583"


def test_line_143_routes_leave_the_map_east(routes):
    r143 = {i: r for i, r in routes.items() if r["line"] == "143"}
    assert sorted(r143) == [9093371, 11533937]                   # one route per direction (#767 A2)
    out, back = r143[9093371], r143[11533937]
    assert out["cut"] == [False, True] and back["cut"] == [True, False]
    for r in (out, back):
        assert 7000 < r["len"] < 9000 and len(r["stops"]) == 9
        assert "8580562" not in [s["uic"] for s in r["stops"]]  # Ritanne lies beyond the east edge (A3)
    assert out["stops"][0]["uic"] == "8572748" and out["stops"][-1]["uic"] == "8572416"
    assert back["stops"][0]["uic"] == "8572416" and back["stops"][-1]["uic"] == "8572748"


def test_line_134_stays_inside_the_map(routes):
    r134 = {i: r for i, r in routes.items() if r["line"] == "134"}
    assert sorted(r134) == [9093370, 11530930]
    for r in r134.values():
        assert r["cut"] == [False, False] and 8000 < r["len"] < 9500 and len(r["stops"]) == 13
    assert routes[9093370]["stops"][0]["uic"] == "8572748" and routes[11530930]["stops"][0]["uic"] == "8500583"


def test_line_135_leaves_the_map_east_of_frick(routes):
    r135 = {i: r for i, r in routes.items() if r["line"] == "135"}
    assert sorted(r135) == [367215, 10888046, 10888047, 10888048, 20345371, 20345372]
    for i in (367215, 10888047, 20345371):               # Frick Bahnhof, out of the map (Aarau, Laufenburg)
        assert r135[i]["cut"] == [False, True] and r135[i]["stops"][0]["uic"] == "8500583"
    for i in (10888046, 10888048, 20345372):             # into the map, ending at Frick Bahnhof
        assert r135[i]["cut"] == [True, False] and r135[i]["stops"][-1]["uic"] == "8500583"
    assert all(len(r["stops"]) in (3, 4) and r["len"] < 2500 for r in r135.values())
    assert all(len(r["stops"]) >= 2 for r in routes.values())     # servable (#808)


def test_line_133_stops_at_the_right_kerb(routes):
    for r in routes.values():
        line = shapely.LineString(r["pts"])
        for s in r["stops"]:
            p = line.interpolate(s["s"])
            dx, dz = math.cos(s["rot"]), math.sin(s["rot"])
            side = (s["x"] - p.x) * -dz + (s["z"] - p.y) * dx          # > 0: right of travel
            assert side > 0 and 2.0 < math.hypot(s["x"] - p.x, s["z"] - p.y) < 8.0


def test_timetable_matches_the_world():
    tt, wf = DATA / "timetable_hochrhein.json", DATA / "world_hochrhein.json"
    if not tt.exists():
        pytest.skip("timetable not generated yet")
    t, w = json.loads(tt.read_text(encoding="utf-8")), json.loads(wf.read_text(encoding="utf-8"))
    stops = {r["id"]: [s["uic"] for s in r["stops"]] for r in w["busRoutes"]}
    trips = [x for x in t["trips"] if x["line"] == "133"]
    assert len(trips) == 14 and sorted(Counter(x["route"] for x in trips).values()) == [7, 7]
    for x in trips:
        assert len(x["calls"]) == 11 and all(c[0] in stops[x["route"]] for c in x["calls"])
        times = [v for c in x["calls"] for v in c[1:]]
        assert times == sorted(times)
    t143 = [x for x in t["trips"] if x["line"] == "143"]
    if t143:   # #767: data rebuilt with line 143 (gtfs_fp2026_20261104.zip, --date 2026-11-10)
        assert len(t143) == 83 and dict(Counter(x["route"] for x in t143)) == {11533937: 42, 9093371: 41}
        assert sum(x["fromOutside"] for x in t143) == 42 and sum(x["toOutside"] for x in t143) == 40
        for x in t143:
            assert all(c[0] in stops[x["route"]] for c in x["calls"])
            times = [v for c in x["calls"] for v in c[1:]]
            assert times == sorted(times)
    for line, counts, out_n, in_n in (("134", {11530930: 28, 9093370: 27}, 0, 0),
                                      ("135", {367215: 34, 10888046: 31, 10888047: 30, 10888048: 33, 20345371: 4, 20345372: 5}, 68, 69)):
        own = [x for x in t["trips"] if x["line"] == line]
        if not own:   # #808: until the data rebuild
            continue
        assert dict(Counter(x["route"] for x in own)) == counts
        assert sum(x["toOutside"] for x in own) == out_n and sum(x["fromOutside"] for x in own) == in_n
        for x in own:
            assert all(c[0] in stops[x["route"]] for c in x["calls"])
            times = [v for c in x["calls"] for v in c[1:]]
            assert times == sorted(times)
